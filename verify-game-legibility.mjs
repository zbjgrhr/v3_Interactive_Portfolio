import {chromium} from 'playwright';
import fs from 'node:fs';
const out='../../outputs/map-report-implementation';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',err=>errors.push(err.message));
await page.goto('http://127.0.0.1:8789/map-preview/?review=map-teleport-detail');
await page.locator('.teleport-report-opening').waitFor();await page.waitForTimeout(2000);
await page.locator('.teleport-report-opening>a img').evaluate(img=>img.decode());
await page.screenshot({path:out+'/game-opening-journal.png'});
const opening=await page.locator('.teleport-report-opening').evaluate(el=>({conceptBeforeReport:!!(el.compareDocumentPosition(document.querySelector('.map-report'))&Node.DOCUMENT_POSITION_FOLLOWING),image:el.querySelector('a img').getAttribute('data-original-src')}));
await page.locator('.map-report__toc a[href="#section-9"]').click();await page.waitForTimeout(1800);
await page.screenshot({path:out+'/game-body-journal.png'});
const surfaces=await page.locator('.map-report__body,.map-report__toc').evaluateAll(els=>els.map(el=>getComputedStyle(el).backgroundColor));
if(!surfaces.includes('rgb(32, 45, 40)')||!surfaces.includes('rgb(28, 41, 35)'))throw Error('Night-map surfaces missing');
if(!opening.conceptBeforeReport)throw Error('Concept image must precede the report');
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:8789/map-preview/?review=map-teleport-detail');await page.waitForTimeout(2300);
await page.screenshot({path:out+'/game-mobile-journal.png'});
const mobileOverflow=await page.locator('.project-detail__panel').evaluate(el=>el.scrollWidth>el.clientWidth+1);
if(mobileOverflow)throw Error('Game panel overflows on mobile');
await page.goto('http://127.0.0.1:8789/portfolio/map-teleport/');await page.locator('.report-reader__concept img').evaluate(img=>img.decode());
await page.screenshot({path:out+'/reading-opening-revised.png'});
await page.getByRole('button',{name:'Switch to English',exact:true}).click();await page.waitForTimeout(300);
const localized=await page.locator('.report-reader__concept img').getAttribute('src');
if(!localized.includes('/localized/en/'))throw Error('Concept image English mapping lost');
if(errors.length)throw Error(errors.join('\n'));
fs.writeFileSync(out+'/legibility-check.json',JSON.stringify({opening,surfaces,mobileOverflow,localized,errors},null,2));
await browser.close();console.log('Concept-first opening, night-map game surfaces, mobile layout and English concept image passed.');
